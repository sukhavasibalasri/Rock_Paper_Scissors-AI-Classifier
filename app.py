if not os.path.exists(model_path):
  with st.spinner('Downloading model from Google Drive... Please wait.'):
    url = f'https://drive.google.com/uc?id={file_id}'
    gdown.download(url, model_path, quiet=False)

import streamlit as st
import tensorflow as tf
from tensorflow.keras.models import load_model
import numpy as np
import cv2

# Page title and description
st.title("✌️ Rock, Paper, Scissors AI Classifier")
st.write("Take a picture using your webcam to test your deep learning model!")

# 1. Load your trained model file (Make sure RPStest.h5 is in the same folder!)
@st.cache_resource
def get_model():
    return load_model("RPStest.h5")

try:
    model = get_model()
except Exception as e:
    st.error("Could not find 'RPStest.h5'. Please make sure your model file is in the same folder as app.py!")
    st.stop()

# Categories mapping
categories = {0: "rock", 1: "paper", 2: "scissors"}

# 2. Camera widget to capture a photo
picture = st.camera_input("Take a picture of your hand gesture")

if picture is not None:
    # Read the image bytes using OpenCV
    bytes_data = picture.getvalue()
    cv2_img = cv2.imdecode(np.frombuffer(bytes_data, np.uint8), cv2.IMREAD_COLOR)

    # Preprocess the image to match what your CNN expects (300x300 pixels, normalized)
    img_rgb = cv2.cvtColor(cv2_img, cv2.COLOR_BGR2RGB)
    img_resized = cv2.resize(img_rgb, (300, 300))
    img_normalized = img_resized.astype("float32") / 255.0
    img_reshaped = np.expand_dims(img_normalized, axis=0)

    # 3. Make prediction with your deep learning model
    prediction = model.predict(img_reshaped)
    predicted_index = np.argmax(prediction)
    confidence = np.max(prediction) * 100
    result_text = categories[predicted_index]

    # 4. Display the results nicely on the interface
    st.markdown("---")
    st.markdown(f"### 🤖 Prediction: **{result_text.upper()}**")
    st.markdown(f"#### 📊 Confidence: **{confidence:.2f}%**")